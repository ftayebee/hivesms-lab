<?php

namespace App\Services\SenderId;

use App\Exceptions\AppException;
use App\Support\ErrorCode;
use Illuminate\Contracts\Filesystem\Filesystem;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

/**
 * Supporting documents (port of services/storage storeDocument). Validated by size, declared type,
 * extension AND magic bytes; stored under a random, organization-scoped key on a private disk
 * (never web-accessible; downloads go through authenticated, tenant-checked endpoints).
 * Keys use the Node layout (orgs/<org>/<folder>/<uuid>.<ext>) so existing files keep resolving
 * when the disk points at the same storage.
 */
class DocumentStorage
{
    private const TYPES = [
        'application/pdf' => ['ext' => ['pdf'], 'magic' => ['%PDF']],
        'image/png' => ['ext' => ['png'], 'magic' => ["\x89PNG"]],
        'image/jpeg' => ['ext' => ['jpg', 'jpeg'], 'magic' => ["\xFF\xD8\xFF"]],
    ];

    private function disk(): Filesystem
    {
        return Storage::disk((string) config('smsflow.uploads.disk', 'local'));
    }

    /** @return array{key: string, name: string, size: int, contentType: string} */
    public function store(string $organizationId, UploadedFile $file, string $folder): array
    {
        $name = $file->getClientOriginalName();
        if ($file->getSize() === 0) {
            throw new AppException(ErrorCode::VALIDATION_ERROR, "{$name} is empty.", ['field' => 'documents']);
        }
        if ($file->getSize() > (int) config('smsflow.uploads.document_max_bytes')) {
            throw new AppException(ErrorCode::VALIDATION_ERROR, "{$name} is larger than 5 MB.", ['field' => 'documents']);
        }
        $type = (string) $file->getMimeType(); // sniffed by fileinfo, not the client header
        $rule = self::TYPES[$type] ?? null;
        $ext = strtolower($file->getClientOriginalExtension());
        if (! $rule || ! in_array($ext, $rule['ext'], true)) {
            throw new AppException(ErrorCode::VALIDATION_ERROR, "{$name}: only PDF, PNG or JPG files are accepted.", ['field' => 'documents']);
        }
        $head = (string) file_get_contents($file->getRealPath(), false, null, 0, 8);
        $magicOk = false;
        foreach ($rule['magic'] as $sig) {
            $magicOk = $magicOk || str_starts_with($head, $sig);
        }
        if (! $magicOk) {
            throw new AppException(ErrorCode::VALIDATION_ERROR, "{$name} does not look like a valid ".strtoupper($ext).' file.', ['field' => 'documents']);
        }
        $key = "orgs/{$organizationId}/{$folder}/".Str::uuid().".{$ext}";
        $this->disk()->put($key, (string) file_get_contents($file->getRealPath()));
        $safeName = mb_substr(preg_replace('/[^\w.\- ]+/u', '_', $name) ?? 'document', 0, 120);

        return ['key' => $key, 'name' => $safeName, 'size' => (int) $file->getSize(), 'contentType' => $type];
    }

    public function get(string $key): ?string
    {
        if (str_contains($key, '..')) {
            return null; // keys are generated by us; refuse anything that looks like traversal
        }

        return $this->disk()->exists($key) ? $this->disk()->get($key) : null;
    }

    public function delete(string $key): void
    {
        if (! str_contains($key, '..')) {
            $this->disk()->delete($key);
        }
    }
}
